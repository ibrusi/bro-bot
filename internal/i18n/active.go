package i18n

import "sync/atomic"

// active — язык интерфейса, выбранный пользователем командой /language.
//
// Бот работает с одним администратором (authMiddleware пускает только его личный
// чат), поэтому язык интерфейса — одно глобальное значение, а не свойство чата.
// Владелец значения — этот пакет: так его может прочитать и домен, которому
// нельзя зависеть от config, и config, который хранит его в базе.
//
// Код представления всё равно получает язык параметром: это делает форматирование
// проверяемым в тестах и не помешает, если однажды у бота появится несколько
// пользователей с разными языками. Active() — для немногих мест в глубине домена,
// куда параметр не дотянуть.
var active atomic.Value

// Active возвращает текущий язык интерфейса.
func Active() string {
	if lang, ok := active.Load().(string); ok && lang != "" {
		return lang
	}
	return Default
}

// SetActive запоминает выбранный язык. Незнакомый код языка заменяется языком
// по умолчанию, поэтому значение из базы можно передавать сюда без проверки.
func SetActive(lang string) string {
	normalized := Normalize(lang)
	active.Store(normalized)
	return normalized
}
